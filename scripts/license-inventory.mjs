#!/usr/bin/env node
/**
 * Writes docs/DEPENDENCY_INVENTORY.md from the installed node_modules tree
 * (production and development), plus the non-npm components.
 */
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const nm = join(ROOT, "node_modules");
const rows = new Map();

function visit(dir, depth) {
  if (!existsSync(dir) || depth > 3) return;
  for (const entry of readdirSync(dir)) {
    if (entry.startsWith(".")) continue;
    const full = join(dir, entry);
    if (entry.startsWith("@")) {
      visit(full, depth);
      continue;
    }
    const pkgJson = join(full, "package.json");
    if (existsSync(pkgJson)) {
      try {
        const pkg = JSON.parse(readFileSync(pkgJson, "utf8"));
        if (pkg.name && pkg.version && !pkg.name.startsWith("@apprentice/")) {
          const license = typeof pkg.license === "string" ? pkg.license : pkg.license?.type ?? (Array.isArray(pkg.licenses) ? pkg.licenses.map((l) => l.type).join("/") : "UNKNOWN");
          rows.set(`${pkg.name}@${pkg.version}`, { name: pkg.name, version: pkg.version, license });
        }
      } catch {
        // ignore unreadable manifests
      }
      const nested = join(full, "node_modules");
      if (existsSync(nested) && statSync(nested).isDirectory()) visit(nested, depth + 1);
    }
  }
}
visit(nm, 0);
const sorted = [...rows.values()].sort((a, b) => a.name.localeCompare(b.name));
const counts = {};
for (const r of sorted) counts[r.license] = (counts[r.license] ?? 0) + 1;
const lines = [
  "# Dependency and license inventory",
  "",
  `Generated by scripts/license-inventory.mjs on ${new Date().toISOString().slice(0, 10)}. ${sorted.length} npm packages (production and development).`,
  "",
  "## License summary",
  "",
  "| License | Count |",
  "|---|---|",
  ...Object.entries(counts).sort((a, b) => b[1] - a[1]).map(([k, v]) => `| ${k} | ${v} |`),
  "",
  "## Non-npm components",
  "",
  "| Component | Version | License |",
  "|---|---|---|",
  "| Tencent UI-Mate reference code (vendored) | commit 1cb9e1e | Apache-2.0 |",
  "| Tencent UI-Mate-9B weights (downloaded separately by the user) | bartowski GGUF Q6_K | Apache-2.0 |",
  "| llama.cpp runtime (downloaded separately) | b10752 | MIT |",
  "| Swift helper | this repo | Apache-2.0 |",
  "",
  "## npm packages",
  "",
  "| Package | Version | License |",
  "|---|---|---|",
  ...sorted.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`),
  ""
];
writeFileSync(join(ROOT, "docs", "DEPENDENCY_INVENTORY.md"), lines.join("\n"));
console.log(`Wrote docs/DEPENDENCY_INVENTORY.md (${sorted.length} packages)`);
